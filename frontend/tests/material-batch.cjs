const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { chromium, expect } = require('@playwright/test');
const backend = path.resolve(__dirname, '../../backend');
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'minex-batch-browser-'));
process.env.DB_CLIENT = 'sqlite';
process.env.SQLITE_PATH = path.join(folder, 'test.db');
process.env.JWT_SECRET = crypto.randomBytes(48).toString('hex');
delete process.env.MYSQL_HOST;
delete process.env.INITIAL_ADMIN_PASSWORD;
const jwt = require(path.join(backend, 'node_modules/jsonwebtoken'));
const { query, queryOne, closeDatabase } = require(path.join(backend, 'dist/config/db'));
const { runMigrations } = require(path.join(backend, 'dist/database/migrate'));
const { MaterialService } = require(path.join(backend, 'dist/services/MaterialService'));
const { app } = require(path.join(backend, 'dist/server'));
let server, browser;
(async () => {
  await runMigrations();
  const user = { nome: 'Administrador', matricula: 'BATCH-ADMIN', nivel_acesso: 'ADMINISTRADOR' };
  user.id = (await query('INSERT INTO usuarios (nome,matricula,nivel_acesso,senha_hash) VALUES (?,?,?,?)', [user.nome,user.matricula,user.nivel_acesso,'unused']))[0].id;
  const token = jwt.sign({ id: user.id }, process.env.JWT_SECRET);
  const existing = await MaterialService.criar({ nome: 'Lanterna existente', codigo_interno: 'LM-050', codigo_barras: 'BAR-050', patrimonio: 'ANTIGO' });
  await query("UPDATE materiais SET status='EM_USO' WHERE id=?", [existing.id]);
  server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  const base = 'http://127.0.0.1:' + server.address().port;
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(({token,user}) => {
    localStorage.setItem('casa_da_lanterna_token',token); localStorage.setItem('casa_da_lanterna_user',JSON.stringify(user));
  }, {token,user});
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/cadastro');
  await page.getByRole('button', { name: 'Materiais', exact: true }).click();
  await expect(page.getByRole('button', {name:/Vincular código de barras/})).toHaveCount(1);
  await page.getByRole('button', { name: 'Novo material', exact: true }).click();
  await expect(page.getByRole('dialog').getByLabel('Patrimônio', {exact:true})).toHaveValue('MINA-UG');
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('button', { name: 'Cadastrar 300 Equipamentos', exact: true }).click();
  let modal = page.getByRole('dialog', { name: 'Cadastro em Lote', exact: true });
  await modal.getByRole('button', { name: 'Verificar conflitos e gerar prévia', exact: true }).click();
  await expect(modal.getByRole('status')).toContainText('300 equipamentos · 299 novos · 1 conflitos');
  assert.equal((await queryOne('SELECT COUNT(*) AS n FROM materiais')).n, 1);
  const confirm = modal.getByRole('button', { name: 'Confirmar cadastro de 299 equipamentos', exact: true });
  await expect(confirm).toBeDisabled();
  await modal.getByRole('checkbox').check();
  fs.mkdirSync(path.resolve(__dirname, '../../test-results'), {recursive:true});
  await page.screenshot({path:path.resolve(__dirname,'../../test-results/lote-previa-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await expect(confirm).toBeInViewport({ratio:1});
  await page.screenshot({path:path.resolve(__dirname,'../../test-results/lote-previa-mobile.png'),fullPage:true});
  await confirm.click();
  await expect(modal.getByRole('status')).toContainText('299 criados · 1 ignorados · 0 erros');
  await modal.getByRole('button', {name:'Fechar',exact:true}).last().click();
  await page.setViewportSize({width:1440,height:1000});
  await expect(page.getByText('LM-001', {exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Patrimônio MINA-UG',exact:true}).click();
  modal = page.getByRole('dialog', {name:'Patrimônio MINA-UG',exact:true});
  await modal.getByRole('button', {name:'Conferir itens cadastrados',exact:true}).click();
  await expect(modal.getByRole('cell', {name:'ANTIGO',exact:true})).toBeVisible();
  await expect(modal.getByRole('button', {name:'Aplicar patrimônio MINA-UG',exact:true})).toBeDisabled();
  await modal.getByRole('checkbox').check();
  await modal.getByRole('button', {name:'Aplicar patrimônio MINA-UG',exact:true}).click();
  await expect(modal.getByRole('status')).toContainText('1 itens atualizados');
  const saved = await MaterialService.buscarPorId(existing.id);
  assert.equal(saved.status,'EM_USO'); assert.equal(saved.codigo_barras,'BAR-050'); assert.equal(saved.patrimonio,'MINA-UG');
  await modal.getByRole('button', {name:'Fechar',exact:true}).last().click();
  await expect(page.getByRole('button',{name:'Etiquetas PDF A4',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Teste de leitura',exact:true})).toBeVisible();
  await page.screenshot({path:path.resolve(__dirname,'../../test-results/materiais-mina-ug.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: prévia sem gravação, conflitos, confirmação, 300 equipamentos, patrimônio, TAGs preservadas e códigos de barras restaurados em desktop e mobile.');
})().catch(error => {console.error(error);process.exitCode=1;}).finally(async () => {
  if(browser) await browser.close(); if(server) await new Promise(resolve=>server.close(resolve)); await closeDatabase();
});
