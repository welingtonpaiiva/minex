const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),crypto=require('node:crypto');
const assert=require('node:assert/strict');
const {chromium,expect}=require('@playwright/test');
const backend=path.resolve(__dirname,'../../backend');
process.env.DB_CLIENT='sqlite';
process.env.SQLITE_PATH=path.join(fs.mkdtempSync(path.join(os.tmpdir(),'minex-code-return-browser-')),'test.db');
process.env.JWT_SECRET=crypto.randomBytes(48).toString('hex');
delete process.env.MYSQL_HOST;delete process.env.INITIAL_ADMIN_PASSWORD;
const jwt=require(path.join(backend,'node_modules/jsonwebtoken'));
const {query,queryOne,closeDatabase}=require(path.join(backend,'dist/config/db'));
const {runMigrations}=require(path.join(backend,'dist/database/migrate'));
const {MaterialService}=require(path.join(backend,'dist/services/MaterialService'));
const {EmprestimoService}=require(path.join(backend,'dist/services/EmprestimoService'));
const {quantityMove}=require(path.join(backend,'dist/services/QuantityService'));
const {app}=require(path.join(backend,'dist/server'));
let server,browser;
(async()=>{
  await runMigrations();
  const user={nome:'Operador',matricula:'CODE-OP',nivel_acesso:'OPERADOR'};
  user.id=(await query('INSERT INTO usuarios (nome,matricula,nivel_acesso,senha_hash) VALUES (?,?,?,?)',[user.nome,user.matricula,user.nivel_acesso,'unused']))[0].id;
  const token=jwt.sign({id:user.id},process.env.JWT_SECRET);
  const people=[];
  for(const [name,number]of [['Ana Costa','CODE-ANA'],['Bruno Lima','CODE-BRUNO']])people.push((await query('INSERT INTO colaboradores (nome,matricula,setor) VALUES (?,?,?)',[name,number,'Subsolo']))[0].id);
  const lamp=await MaterialService.criar({nome:'Lanterna',codigo_interno:'LM-003',codigo_barras:'LM-003'});
  const pending=await MaterialService.criar({nome:'Rádio',codigo_interno:'RP-001',codigo_barras:'BAR-RADIO'});
  await EmprestimoService.realizarSaida({colaboradorId:people[0],operadorId:user.id,materiaisCodigos:['LM-003','RP-001'],requestId:crypto.randomUUID()});
  await EmprestimoService.realizarEntrada({colaboradorId:people[0],operadorId:user.id,materiaisCodigos:['RP-001'],requestId:crypto.randomUUID(),condicao:'CONFERENCIA'});
  const bulk=await MaterialService.criar({nome:'Luvas',codigo_interno:'LUV-001'});
  await query("UPDATE materiais SET tipo_controle='QUANTIDADE',saldo_disponivel=20 WHERE id=?",[bulk.id]);
  for(const person of people)await quantityMove({tipo:'RETIRADA',material_id:bulk.id,colaborador_id:person,quantidade:4,requestId:crypto.randomUUID()},user.id);
  server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
  const base='http://127.0.0.1:'+server.address().port;
  browser=await chromium.launch({channel:'chrome',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.addInitScript(({token,user})=>{localStorage.setItem('casa_da_lanterna_token',token);localStorage.setItem('casa_da_lanterna_user',JSON.stringify(user));},{token,user});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/entrada');await page.getByRole('button',{name:'Fechar leitor NFC',exact:true}).click();
  await page.getByRole('button',{name:'Devolver por código',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Devolução por código',exact:true})).toBeVisible();
  const input=page.getByRole('textbox',{name:'Código do item para devolução',exact:true});
  const scan=async code=>{await input.fill(code);await input.press('Enter');};
  await scan('INEXISTENTE');await expect(page.getByRole('alert')).toContainText('não cadastrado');
  await scan('LM-003');await expect(page.getByRole('heading',{name:'Responsável pela retirada',exact:true})).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:/Ana Costa/})).toHaveAttribute('aria-pressed','true');
  const confirm=page.getByRole('button',{name:'Confirmar devolução por código',exact:true});
  await expect(confirm).toBeDisabled();
  // Alterar o código digitado elimina a confirmação do material anterior.
  await input.fill('RP-001');await expect(confirm).toHaveCount(0);
  await scan('LM-003');await page.getByRole('checkbox').check();
  const artifacts=path.resolve(__dirname,'../../test-results');fs.mkdirSync(artifacts,{recursive:true});
  await page.screenshot({path:path.join(artifacts,'devolucao-por-codigo-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await confirm.scrollIntoViewIfNeeded();await expect(confirm).toBeInViewport({ratio:1});
  await page.screenshot({path:path.join(artifacts,'devolucao-por-codigo-mobile.png'),fullPage:true});
  await confirm.click();await expect(page.locator('.notice.success')).toContainText('LM-003');
  await expect(page.locator('.notice.success')).toContainText('Conferidos e aptos.');
  assert.equal((await MaterialService.buscarPorId(lamp.id)).status,'DISPONIVEL');
  await scan('LM-003');await expect(page.getByText('Este item não possui devolução ou conferência pendente.',{exact:true})).toBeVisible();
  await expect(confirm).toHaveCount(0);
  await page.setViewportSize({width:1440,height:1000});
  await scan('BAR-RADIO');await expect(page.getByRole('heading',{name:'Liberar item conferido',exact:true})).toBeVisible();
  await page.getByLabel('Justificativa da liberação',{exact:true}).fill('Conferido e apto pelo operador.');
  await page.getByRole('checkbox').check();await page.getByRole('button',{name:'Liberar no estoque',exact:true}).click();
  await expect(page.locator('.notice.success')).toContainText('RP-001');
  assert.equal((await MaterialService.buscarPorId(pending.id)).status,'DISPONIVEL');
  assert.equal((await queryOne("SELECT COUNT(*) AS n FROM movimentacoes WHERE material_id=? AND tipo='ENTRADA'",[pending.id])).n,1);
  await scan('LUV-001');await expect(page.getByText('Selecione de qual empréstimo está recebendo as unidades.',{exact:true})).toBeVisible();
  await expect(confirm).toHaveCount(0);
  await page.getByRole('button',{name:/Bruno Lima/}).click();
  await page.getByRole('spinbutton',{name:'Quantidade a receber por código',exact:true}).fill('2');
  await page.getByRole('checkbox').check();await confirm.click();
  await expect(page.locator('.notice.success')).toContainText('Bruno Lima');
  assert.equal((await MaterialService.buscarPorId(bulk.id)).saldo_disponivel,14);
  assert.equal((await queryOne('SELECT quantidade-devolvida AS restante FROM emprestimos_quantidade WHERE material_id=? AND colaborador_id=?',[bulk.id,people[1]])).restante,2);
  assert.deepEqual(errors,[]);
  console.log('PASS: TAG digitada, sem NFC, liberação de conferência, quantidades por responsável, desktop e mobile.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{
  if(browser)await browser.close();if(server)await new Promise(resolve=>server.close(resolve));await closeDatabase();
});
