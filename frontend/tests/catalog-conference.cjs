const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),crypto=require('node:crypto');
const assert=require('node:assert/strict');
const {chromium,expect}=require('@playwright/test');
const backend=path.resolve(__dirname,'../../backend');
process.env.DB_CLIENT='sqlite';
process.env.SQLITE_PATH=path.join(fs.mkdtempSync(path.join(os.tmpdir(),'minex-conference-')),'test.db');
process.env.JWT_SECRET=crypto.randomBytes(48).toString('hex');
delete process.env.MYSQL_HOST;delete process.env.INITIAL_ADMIN_PASSWORD;
const jwt=require(path.join(backend,'node_modules/jsonwebtoken'));
const {query,queryOne,closeDatabase}=require(path.join(backend,'dist/config/db'));
const {runMigrations}=require(path.join(backend,'dist/database/migrate'));
const {MaterialService}=require(path.join(backend,'dist/services/MaterialService'));
const {app}=require(path.join(backend,'dist/server'));
let server,browser;
(async()=>{
  await runMigrations();
  const user={nome:'Operador',matricula:'OP-CONFERENCE',nivel_acesso:'OPERADOR'};
  user.id=(await query('INSERT INTO usuarios (nome,matricula,nivel_acesso,senha_hash) VALUES (?,?,?,?)',[user.nome,user.matricula,user.nivel_acesso,'unused']))[0].id;
  const token=jwt.sign({id:user.id},process.env.JWT_SECRET);
  const item=await MaterialService.criar({nome:'Lanterna',codigo_interno:'LM-003'});
  await query("UPDATE materiais SET status='AGUARDANDO_CONFERENCIA' WHERE id=?",[item.id]);
  const bulk=await MaterialService.criar({nome:'Luvas',codigo_interno:'LUV-001'});
  await query("UPDATE materiais SET tipo_controle='QUANTIDADE',saldo_disponivel=4,saldo_conferencia=3,saldo_manutencao=1 WHERE id=?",[bulk.id]);
  server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
  const base='http://127.0.0.1:'+server.address().port;
  browser=await chromium.launch({channel:'chrome',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.addInitScript(({token,user})=>{localStorage.setItem('casa_da_lanterna_token',token);localStorage.setItem('casa_da_lanterna_user',JSON.stringify(user));},{token,user});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/estoque?status=AGUARDANDO_CONFERENCIA');
  await page.getByRole('button',{name:'Conferir',exact:true}).click();
  const modal=page.getByRole('dialog');
  await expect(modal.getByRole('option',{name:'Inativo',exact:true})).toHaveCount(0);
  await modal.getByLabel('Justificativa',{exact:true}).fill('Conferência física concluída pelo operador.');
  await modal.getByRole('button',{name:'Confirmar ajuste',exact:true}).click();
  await expect(modal).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Conferir',exact:true})).toHaveCount(0);
  assert.equal((await MaterialService.buscarPorId(item.id)).status,'DISPONIVEL');
  assert.equal((await queryOne("SELECT usuario_id FROM auditoria WHERE acao='CONFERENCIA_ESTOQUE'")).usuario_id,user.id);
  for(const route of ['/quantidades','/operacoes']){
    await page.goto(base+route);
    if(route==='/operacoes')await page.getByRole('button',{name:/Materiais por quantidade/i}).click();
    await page.getByRole('button',{name:'Conferir',exact:true}).click();
    const dialog=page.getByRole('dialog');
    await expect(dialog.locator('option[value="AJUSTE"]')).toHaveCount(0);
    await expect(dialog.locator('option[value="MANUTENCAO"]')).toHaveCount(0);
    await dialog.getByRole('spinbutton').fill('1');
    await dialog.getByLabel('Justificativa',{exact:true}).fill('Unidade conferida pelo operador.');
    await dialog.getByRole('button',{name:'Confirmar',exact:true}).click();
    await expect(dialog).toHaveCount(0);
  }
  const saved=await MaterialService.buscarPorId(bulk.id);
  assert.equal(saved.saldo_disponivel,6);assert.equal(saved.saldo_conferencia,1);assert.equal(saved.saldo_manutencao,1);
  assert.deepEqual(errors,[]);
  console.log('PASS: operador confere equipamentos e unidades nas duas telas; ajustes administrativos continuam restritos.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{
  if(browser)await browser.close();if(server)await new Promise(resolve=>server.close(resolve));await closeDatabase();
});
